import torch.nn as nn

from project_spectrogram.module.channel_attention import ChannelAttention
from project_spectrogram.module.spatial_attention import SpatialAttention


class CBAM(nn.Module):
    def __init__(self, in_planes, ratio=16, kernel_size=7):
        super().__init__()
        self.ca = ChannelAttention(in_planes, ratio)
        self.sa = SpatialAttention(kernel_size)

    def forward(self, x):
        x = x * self.ca(x)
        x = x * self.sa(x)
        return x